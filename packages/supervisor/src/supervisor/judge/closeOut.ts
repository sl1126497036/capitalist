/**
 * 结束与验收口径，由工作进程提示词与监工判定层共用。
 *
 * 判据以“本单要求的产出物”为准：不预设产出形态（文件、数据、页面、台账、命令输出、结论都算），
 * 也不预设任务类型。执行侧与审查侧共用这一份，两处各写一套必然漂。
 */

/**
 * 结束口径正文，各派单入口与审查侧共用。
 * @param heading 区块标题；各入口块序不同，序号由调用方传入。
 */
export function closeOutRules(heading = "【四、怎么算做完】"): string[] {
  return [
    heading,
    "  1. 结束前执行两项核对：按本单要求核对产出物；执行与核对直接相关的检查。",
    "  2. 不扩大核对范围：本单没要求的批量复查、全量回归、附加证据一律不做，也不作为结束前置；",
    "     执行中发现的既有问题如实写进报告，不因此阻塞结束。",
    "  3. 判据是产出物本身，不是自述。产出物形态由任务性质决定：文件、数据、页面、台账、",
    "     命令输出或一段可复现的结论都算，不以截图、日志量为准。",
    "  4. 确实要跑命令时必须带超时与无输出判定：超时或持续无新输出时立即中止，",
    "     并在报告中写明超时命令、超时阈值及末尾输出。",
    "  5. 报告要点明产出物的位置与形态，并逐条对照本单要求说明如何满足。",
    "     `--note` 写过程，`--evidence` 写可核对的内容（产出物位置、执行的核对与结果），",
    "     不得使用“已优化”“没问题”等无法核对的表述。",
    "  6. 本单声明验收判据时以该判据为准；未声明时适用本节通用口径。",
    /* `capitalist report` 在原地等裁决；被打回时同一进程继续修改，不重开单。 */
    "  7. `capitalist report ... done` 将阻塞等待监工裁决：",
    "     · 通过 -> 完成；",
    "     · 裁决不通过 -> 带原因返回并给出非零退出码，在本进程内继续修改，不重开、不重做；",
    "     · 裁决未返回 -> 继续执行剩余部分，不重复上报；",
    "     · 只有明确的卡点（capitalist ask）和异常才停止执行。",
  ];
}

/** 审查侧的验收口径：明确“没做本单未要求的额外核对”不构成打回理由。 */
export function acceptanceFacts(): string[] {
  return [
    "【验收口径】",
    "  · 以产出物证据为主：报告须写明产出物的位置与形态，以及是否逐条符合本单要求。",
    "  · 本单声明了验收判据时以它为准，通用口径只作兜底。",
    "  · 可执行核对为辅：命令、比对或检查执行完成且结果一致。",
    "  · 本单未要求的批量复查、全量回归、附加证据未做，以及报告如实记录的既有或环境问题，均不构成退回理由。",
    "  · 退回条件：与要求不符、核对未落实、无可核对证据。",
  ];
}
