/**
 * 结束与验收口径，由工作进程提示词与监工判定层共用。
 * 验收以产出物核对为准，可执行核对为辅，全量测试不作为结束前置。
 */

/**
 * 结束口径正文，各派单入口与审查侧共用。
 * @param heading 区块标题；各入口块序不同，序号由调用方传入。
 */
export function closeOutRules(heading = "【四、怎么算做完】"): string[] {
  return [
    heading,
    "  1. 结束前只做两项：按派单要求核对产出物，执行与核对直接相关的少量命令或检查。",
    "  2. 全量测试、端到端长跑、全量构建校验一律不执行，也不作为结束前置或验收条件；",
    "     既有失败与环境性失败如实写入报告，不因此阻塞结束。",
    "  3. 不要求截图，也不做截图核对；验收以代码复查与相关单元测试为准。",
    "  4. 确实要跑命令时必须带超时与无输出判定：超时或长时间没有新输出就立刻中止，",
    "     并在报告里写清超时的那条命令、超时阈值和最后几行输出。",
    "  5. 报告要点明产出物的位置与形态，并逐条对照派单要求说明如何满足。",
    "     `--note` 写过程，`--evidence` 写可核对的内容（产出物位置、执行的核对与结果），",
    "     不写“已优化”“没问题”这类无法核对的说法。",
    /* `capitalist report` 在原地等裁决；被打回时同一进程继续修改，不重开单。 */
    "  6. `capitalist report ... done` 会在原地等监工裁决：",
    "     · 通过 -> 完成；",
    "     · 被打回 -> 带原因返回并给出非零退出码，**在本进程内继续修改**，不重开、不重做；",
    "     · 裁决还没出 -> 继续执行剩余部分，不重复上报；",
    "     · 只有明确的卡点（capitalist ask）和异常才停止执行。",
  ];
}

/** 审查侧的验收口径，明确未跑全量测试与未附截图不构成打回理由。 */
export function acceptanceFacts(): string[] {
  return [
    "【验收口径】",
    "  · 以产出物证据为主：报告要点明产出物的位置与形态，是否逐条对上派单要求。",
    "  · 可执行核对为辅：命令、测试或比对执行完成且结果一致。",
    "  · 全量测试未跑、全量测试有既有失败、未做端到端长跑、未附截图，都不构成打回理由；",
    "    报告里如实记录的既有/环境性失败同样不构成打回理由。",
    "  · 打回条件：与要求不符、核对未落到位、无可核对证据。",
  ];
}
