/**
 * 结单与验收口径，由工作进程提示词与监工判定层共用。
 * 验收以代码复查与相关单元测试为准，全量测试不作为结单前置。
 */

/**
 * 结单口径正文，各派单入口与审查侧共用。
 * @param heading 区块标题；各入口块序不同，序号由调用方传入。
 */
export function closeOutRules(heading = "【四、怎么算做完】"): string[] {
  return [
    heading,
    "  1. 结单前只做两件事：读改动点自查行为是否符合要求，跑与本次改动直接相关的少量单元测试。",
    "  2. 全量测试、端到端长跑、构建全量校验一律不执行，也不作为结单前置或验收条件；",
    "     既有失败与环境性失败如实写入报告，不因此阻塞结单。",
    "  3. 不要求截图，也不做截图核对；验收以代码复查与相关单元测试为准。",
    "  4. 确实要跑命令时必须带超时与无输出判定：超时或长时间没有新输出就立刻中止，",
    "     并在报告里写清卡住的那条命令、超时阈值和最后几行输出。",
    "  5. 报告要点明改了哪个文件、哪个函数，并逐条对照派单要求说明行为怎么满足。",
    "     `--note` 写过程，`--evidence` 写能核对的东西（改了哪几处 / 跑了什么 / 结果），",
    "     不写“已优化”“没问题”这类无法核对的说法。",
    /* `capitalist report` 在原地等裁决；被打回时同一进程继续修改，不重开单。 */
    "  6. `capitalist report ... done` 会在原地等监工裁决：",
    "     · 通过 -> 收工；",
    "     · 被打回 -> 带原因返回并给出非零退出码，**就在本进程里接着改**，不重开单、不从头再来；",
    "     · 裁决还没出 -> 继续执行剩余部分，不重复上报；",
    "     · 只有明确的卡点（capitalist ask）和异常才停手。",
  ];
}

/** 审查侧的验收口径，明确未跑全量测试与未附截图不构成打回理由。 */
export function acceptanceFacts(): string[] {
  return [
    "【验收口径】",
    "  · 以代码证据为主：报告要点明改了哪个文件、哪个函数，行为是否逐条对上了派单要求。",
    "  · 以与改动直接相关的单元测试为辅：执行完成且结果一致。",
    "  · 全量测试未跑、全量测试有既有失败、未做端到端长跑、未附截图，都不构成打回理由；",
    "    报告里如实记录的既有/环境性失败同样不构成打回理由。",
    "  · 打回条件：行为不符合要求、改动未落到位、无代码证据。",
  ];
}
